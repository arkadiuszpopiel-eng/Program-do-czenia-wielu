// Odtwarzalny zarys lądów Natural Earth 5.1.2, domena publiczna; bez granic i telemetrii.
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const source = new URL('scripts/data/ne_110m_land.geojson', root);
const data = await readFile(source);
const expected = '9e0729ee253ca7d7a5c4ae9395fb1902264c5377c52e224d13dd85010e2835d9';
if (createHash('sha256').update(data).digest('hex') !== expected)
  throw new Error('Niezgodny hash źródła mapy');

function distance(p, a, b) {
  const dx = b[0] - a[0],
    dy = b[1] - a[1];
  const t =
    dx || dy
      ? Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / (dx * dx + dy * dy)))
      : 0;
  return (p[0] - a[0] - t * dx) ** 2 + (p[1] - a[1] - t * dy) ** 2;
}
function simplify(points) {
  if (points.length <= 2) return points;
  let max = 0.09,
    split = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const d = distance(points[i], points[0], points.at(-1));
    if (d > max) {
      max = d;
      split = i;
    }
  }
  return split
    ? [...simplify(points.slice(0, split + 1)).slice(0, -1), ...simplify(points.slice(split))]
    : [points[0], points.at(-1)];
}
// WGS84 lon/lat → równoległe południki/równoleżniki; brak danych liczbowych kodowanych powierzchnią.
const paths = JSON.parse(data).features.flatMap(({ geometry }) => {
  if (geometry.type !== 'Polygon' && geometry.type !== 'MultiPolygon')
    throw new Error('Nieznana geometria');
  const polygons = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
  return polygons.flatMap((p) =>
    p.map(
      (ring) =>
        simplify(ring)
          .map(
            ([lon, lat], i) =>
              `${i ? 'L' : 'M'}${((lon + 180) * 2).toFixed(1)},${((90 - lat) * 2).toFixed(1)}`,
          )
          .join('') + 'Z',
    ),
  );
});
const svg = `<!-- Generated by scripts/cockpit-map.mjs; Natural Earth 5.1.2, public domain. -->\n<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 720 360"><path fill="#64818c" fill-opacity=".65" d="${paths.join('')}"/></svg>\n`;
const target = new URL('apps/desktop/ui/src/lib/components/cockpit/assets/world-land.svg', root);
await mkdir(new URL('./', target), { recursive: true });
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')) !== svg) throw new Error('Mapa wymaga wygenerowania');
} else await writeFile(target, svg);
console.log(`cockpit-map: ${fileURLToPath(target)}, ${Buffer.byteLength(svg)} B`);
