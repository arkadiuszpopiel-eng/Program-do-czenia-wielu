/// Rodzaj rzeczownika następującego po liczbie (domyślnie męski).
pub(crate) fn noun_gender(word: &str) -> Gender {
    let w = word.to_lowercase();
    if FEM_NOUNS.contains(&w.as_str()) {
        Gender::Fem
    } else if NEUT_NOUNS.contains(&w.as_str()) {
        Gender::Neut
    } else {
        Gender::Masc
    }
}
